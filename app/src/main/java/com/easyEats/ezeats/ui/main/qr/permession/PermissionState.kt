package com.easyEats.ezeats.ui.main.qr.permession

/**
 * Enum class representing the possible states of a permission request.
 */
enum class PermissionState {
    /**
     * Represents that the permission has been granted.
     */
    PERMISSION_GRANTED,

    /**
     * Represents that the permission has not been granted.
     */
    PERMISSION_NOT_GRANTED
}
